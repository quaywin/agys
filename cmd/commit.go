package cmd

import (
	"bufio"
	"context"
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/quaywin/agys/pkg/profile"
	"github.com/spf13/cobra"
)

var (
	commitMsg      string
	commitAll      bool
	commitStageAll bool
	commitYes      bool
	commitPush     bool
	commitNoCheck  bool
	commitDryRun   bool
	commitModel    string
	commitEffort   string
	commitPrompt   string
)

var commitCmd = &cobra.Command{
	Use:               "commit [profile_name] [flags]",
	Short:             "Check staged git files with AI and commit using auto-selected or specified profile",
	Long:              `Inspects staged git changes using an AI profile (auto-selected based on 5h Gemini quota or specified), performs a code review check, generates or validates a commit message, and commits the changes.`,
	ValidArgsFunction: CompleteProfileNames,
	Args:              cobra.MaximumNArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		// 1. Check if inside a git repository
		if !profile.IsGitRepository("") {
			return fmt.Errorf("not a git repository (or any of the parent directories)")
		}

		// 2. Stage files if -a / --all or -A / --stage-all is set
		if commitStageAll {
			if err := profile.StageAllFiles(""); err != nil {
				return err
			}
		} else if commitAll {
			if err := profile.StageTrackedFiles(""); err != nil {
				return err
			}
		}

		// 3. Get staged files
		stagedFiles, err := profile.GetStagedFiles("")
		if err != nil {
			return err
		}
		if len(stagedFiles) == 0 {
			fmt.Println("No staged changes found. Use `git add <files>` to stage changes before committing.")
			return nil
		}

		// 4. Determine target profile
		var profileName string
		if len(args) > 0 {
			profileName = args[0]
		} else {
			current, err := profile.GetCurrent()
			if err != nil {
				return err
			}
			if current != "" {
				profileName = current
			} else {
				profileName = profile.AutoProfileKeyword
			}
		}

		var targetProfile string
		if profile.IsAuto(profileName) {
			selected, score, err := profile.SelectBestProfile(cmd.Context())
			if err != nil {
				return fmt.Errorf("auto profile selection failed: %w", err)
			}
			targetProfile = selected
			scoreStr := fmt.Sprintf("%.1f%%", score*100)
			if score < 0 {
				scoreStr = "N/A"
			}
			fmt.Fprintf(os.Stderr, "[agys] Auto-selected profile %q (5h Gemini quota: %s)\n", targetProfile, scoreStr)
		} else {
			exists, _, err := profile.Exists(profileName)
			if err != nil {
				return err
			}
			if !exists {
				return fmt.Errorf("profile %q does not exist. Use `agys add %s` to create it", profileName, profileName)
			}
			targetProfile = profileName
		}

		profileDir, err := profile.GetProfileDir(targetProfile)
		if err != nil {
			return err
		}

		// 5. Get compact staged diff & stat
		stagedDiff, err := profile.GetCompactStagedDiff("")
		if err != nil {
			stagedDiff, err = profile.GetStagedDiff("")
			if err != nil {
				return err
			}
		}
		stagedDiffStat, _ := profile.GetStagedDiffStat("")

		fmt.Fprintf(os.Stderr, "[agys] Inspecting %d staged file(s) under profile %q...\n", len(stagedFiles), targetProfile)

		var finalMessage string
		var checkSummary string

		if commitNoCheck && commitMsg != "" {
			finalMessage = commitMsg
			checkSummary = "Skipped (--no-check specified)."
		} else if commitNoCheck {
			checkSummary = "Skipped (--no-check specified)."
		} else {
			checkCtx, cancelCheck := context.WithTimeout(cmd.Context(), 90*time.Second)
			result, err := profile.RunAgyCommitCheck(checkCtx, profileDir, stagedFiles, stagedDiff, stagedDiffStat, commitMsg, commitNoCheck, commitModel, commitEffort, commitPrompt)
			cancelCheck()
			if err != nil {
				fmt.Fprintf(os.Stderr, "[agys] Warning: AI commit check failed (%v).\n", err)
				if commitMsg != "" {
					finalMessage = commitMsg
				}
				checkSummary = "AI check unavailable."
			} else {
				finalMessage = result.CommitMessage
				checkSummary = result.CheckSummary
			}
		}

		if strings.TrimSpace(finalMessage) == "" {
			if !commitYes {
				reader := bufio.NewReader(os.Stdin)
				fmt.Print("AI was unable to generate a commit message. Enter custom commit message: ")
				customMsg, _ := reader.ReadString('\n')
				customMsg = strings.TrimSpace(customMsg)
				if customMsg == "" {
					return fmt.Errorf("commit message cannot be empty")
				}
				finalMessage = customMsg
			} else {
				return fmt.Errorf("commit failed: no commit message provided or generated by AI")
			}
		}

		useColor := os.Getenv("NO_COLOR") == ""
		hasSecurityRisk := profile.ContainsSecurityRisk(checkSummary)

		// Display Code Review Summary
		if checkSummary != "" {
			if hasSecurityRisk {
				if useColor {
					fmt.Println("\n\033[1;31m┌────────────────────────────────────────────────────────────────────────┐\033[0m")
					fmt.Println("\033[1;31m│  ⚠️  SECURITY WARNING: Potential secrets or security risks detected!   │\033[0m")
					fmt.Println("\033[1;31m└────────────────────────────────────────────────────────────────────────┘\033[0m")
					fmt.Println("\033[1;31m--- Code Review Summary (Security Risk Detected!) ---\033[0m")
				} else {
					fmt.Println("\n[!] SECURITY WARNING: Potential secrets or security risks detected!")
					fmt.Println("--- Code Review Summary ---")
				}
			} else {
				if useColor {
					fmt.Println("\n\033[1;36m--- Code Review Summary ---\033[0m")
				} else {
					fmt.Println("\n--- Code Review Summary ---")
				}
			}
			fmt.Println(checkSummary)
		}

		// Display Proposed Commit Message
		if useColor {
			fmt.Println("\n\033[1;32m--- Proposed Commit Message ---\033[0m")
		} else {
			fmt.Println("\n--- Proposed Commit Message ---")
		}
		fmt.Println(finalMessage)
		fmt.Println()

		if commitDryRun {
			fmt.Println("[agys] Dry-run complete. No changes committed.")
			return nil
		}

		// If a security warning is detected, bypass -y/--yes to force explicit confirmation
		if hasSecurityRisk && commitYes {
			fmt.Println("[agys] ⚠️  Security warning detected in staged changes! Bypassing -y/--yes to require explicit confirmation.")
			commitYes = false
		}

		// Ask for confirmation if not auto-accepted (-y / --yes)
		if !commitYes {
			reader := bufio.NewReader(os.Stdin)
			fmt.Print("Commit with this message? [Y/n/e(dit)]: ")
			input, _ := reader.ReadString('\n')
			input = strings.TrimSpace(strings.ToLower(input))

			if input == "n" || input == "no" {
				fmt.Println("Commit cancelled.")
				return nil
			} else if input == "e" || input == "edit" {
				fmt.Print("Enter custom commit message: ")
				customMsg, _ := reader.ReadString('\n')
				customMsg = strings.TrimSpace(customMsg)
				if customMsg == "" {
					return fmt.Errorf("commit message cannot be empty")
				}
				finalMessage = customMsg
			}
		}

		// Execute Git Commit
		fmt.Printf("[agys] Executing git commit...\n")
		if err := profile.ExecuteGitCommit("", finalMessage); err != nil {
			return err
		}

		// Execute Git Push if -p / --push flag is set
		if commitPush {
			fmt.Printf("[agys] Executing git push...\n")
			return profile.ExecuteGitPush("")
		}

		return nil
	},
}

func init() {
	commitCmd.Flags().StringVarP(&commitMsg, "message", "m", "", "Specify commit message directly")
	commitCmd.Flags().BoolVarP(&commitAll, "all", "a", false, "Automatically stage modified/deleted tracked files before commit (git add -u)")
	commitCmd.Flags().BoolVarP(&commitStageAll, "stage-all", "A", false, "Automatically stage all changes including untracked files before commit (git add -A)")
	commitCmd.Flags().BoolVarP(&commitYes, "yes", "y", false, "Automatically accept commit message and commit without interactive prompt")
	commitCmd.Flags().BoolVarP(&commitPush, "push", "p", false, "Automatically push to current git branch after committing")
	commitCmd.Flags().BoolVar(&commitNoCheck, "no-check", false, "Skip AI code review check")
	commitCmd.Flags().BoolVar(&commitDryRun, "dry-run", false, "Perform AI review and message generation without executing git commit")
	commitCmd.Flags().StringVar(&commitModel, "model", "", "Override model for agy commit check (defaults to latest Gemini Flash)")
	commitCmd.Flags().StringVar(&commitEffort, "effort", "", "Override reasoning effort for agy commit check (defaults to low)")
	commitCmd.Flags().StringVar(&commitPrompt, "prompt", "", "Additional custom prompt instructions for commit check")

	rootCmd.AddCommand(commitCmd)
}
